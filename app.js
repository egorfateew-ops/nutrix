function sumAmountMap(amounts,foodSet){
  let sum=0;
  amounts.forEach((amount,key)=>{const name=key.slice(0,key.lastIndexOf('|'));if(foodSet.has(name))sum+=Number(amount)||0;});
  return sum;
}
